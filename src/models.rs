use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::fmt;
use uuid::Uuid;

/// Severity level of a detected security event, ordered from lowest to highest.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "UPPERCASE")]
pub enum Severity {
    Low,
    Medium,
    High,
    Critical,
}

impl fmt::Display for Severity {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Severity::Low => write!(f, "LOW"),
            Severity::Medium => write!(f, "MEDIUM"),
            Severity::High => write!(f, "HIGH"),
            Severity::Critical => write!(f, "CRITICAL"),
        }
    }
}

/// Classification of a security event.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum EventCategory {
    WebAttack,
    Reconnaissance,
    BruteForce,
    RateLimit,
    LogTampering,
    FileIntegrity,
    WebShell,
    Persistence,
    DockerAnomaly,
    System,
}

impl fmt::Display for EventCategory {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match self {
            EventCategory::WebAttack => "web_attack",
            EventCategory::Reconnaissance => "reconnaissance",
            EventCategory::BruteForce => "brute_force",
            EventCategory::RateLimit => "rate_limit",
            EventCategory::LogTampering => "log_tampering",
            EventCategory::FileIntegrity => "file_integrity",
            EventCategory::WebShell => "web_shell",
            EventCategory::Persistence => "persistence",
            EventCategory::DockerAnomaly => "docker_anomaly",
            EventCategory::System => "system",
        };
        write!(f, "{s}")
    }
}

/// Normalized log entry produced by any `WebServerProvider` or auth log parser.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct UnifiedLogEntry {
    pub timestamp: DateTime<Utc>,
    pub server: String,
    pub client_ip: String,
    pub method: String,
    pub path: String,
    pub status: u16,
    pub user_agent: String,
    pub bytes_sent: u64,
    pub raw_line: String,
    pub is_auth_failure: bool,
}

/// A security incident or alert generated by the detection engine or collectors.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SecurityEvent {
    pub id: String,
    pub timestamp: DateTime<Utc>,
    pub severity: Severity,
    pub category: EventCategory,
    pub title: String,
    pub description: String,
    pub source_ip: Option<String>,
    pub file_path: Option<String>,
    pub rule_id: Option<String>,
    pub raw_snippet: Option<String>,
    pub action_taken: Option<String>,
}

impl SecurityEvent {
    /// Creates a new `SecurityEvent` with a generated UUIDv4 and current UTC timestamp.
    pub fn new(
        severity: Severity,
        category: EventCategory,
        title: impl Into<String>,
        description: impl Into<String>,
    ) -> Self {
        Self {
            id: Uuid::new_v4().to_string(),
            timestamp: Utc::now(),
            severity,
            category,
            title: title.into(),
            description: description.into(),
            source_ip: None,
            file_path: None,
            rule_id: None,
            raw_snippet: None,
            action_taken: None,
        }
    }

    pub fn with_source_ip(mut self, ip: impl Into<String>) -> Self {
        self.source_ip = Some(ip.into());
        self
    }

    pub fn with_file_path(mut self, path: impl Into<String>) -> Self {
        self.file_path = Some(path.into());
        self
    }

    pub fn with_rule_id(mut self, rule_id: impl Into<String>) -> Self {
        self.rule_id = Some(rule_id.into());
        self
    }

    pub fn with_raw_snippet(mut self, snippet: impl Into<String>) -> Self {
        let mut s = snippet.into();
        if s.len() > 512 {
            s.truncate(512);
            s.push_str("...");
        }
        self.raw_snippet = Some(s);
        self
    }

    pub fn with_action_taken(mut self, action: impl Into<String>) -> Self {
        self.action_taken = Some(action.into());
        self
    }
}

/// Record of an IP address blocked by the firewall action layer.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct BannedIp {
    pub ip: String,
    pub reason: String,
    pub banned_at: DateTime<Utc>,
    pub expires_at: Option<DateTime<Utc>>,
    pub permanent: bool,
    pub backend: String,
}

/// Health & configuration status of a detected web server.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WebServerStatus {
    pub name: String,
    pub installed: bool,
    pub running: bool,
    pub config_ok: Option<bool>,
    pub log_paths: Vec<String>,
}

/// Lightweight container metric snapshot from Docker.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DockerContainerMetric {
    pub id: String,
    pub name: String,
    pub status: String,
    pub cpu_percent: f64,
    pub memory_mb: f64,
    pub restart_count: i64,
    pub anomaly: Option<String>,
}

/// Aggregated daemon runtime status shared via IPC and Web GUI.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct DaemonStatus {
    pub hostname: String,
    pub version: String,
    pub uptime_secs: u64,
    pub paused_until: Option<DateTime<Utc>>,
    pub events_processed: u64,
    pub alerts_total: u64,
    pub active_bans: usize,
    pub web_servers: Vec<WebServerStatus>,
    pub docker_containers: Vec<DockerContainerMetric>,
    pub traffic_rps_history: Vec<u64>,
}

/// IPC request sent from `aegis tui`, CLI commands, or Web GUI to the daemon.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "cmd", rename_all = "snake_case")]
pub enum IpcRequest {
    GetStatus,
    GetRecentEvents { limit: usize },
    GetBannedIps,
    BanIp {
        ip: String,
        reason: String,
        duration_secs: Option<u64>,
    },
    UnbanIp { ip: String },
    PauseFim { duration_secs: u64 },
    ResumeFim,
    ReloadWebServer { server: String },
    SubscribeEvents,
}

/// IPC response returned by the daemon.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum IpcResponse {
    Ok { message: String },
    Error { message: String },
    Status { status: DaemonStatus },
    Events { events: Vec<SecurityEvent> },
    BannedIps { ips: Vec<BannedIp> },
    EventPush { event: SecurityEvent },
}

/// Internal collector message sent to the detection engine.
#[derive(Debug, Clone)]
pub enum CollectorMessage {
    LogEntry(UnifiedLogEntry),
    DirectEvent(SecurityEvent),
}
